import os
import warnings
import pandas as pd
import matplotlib.pyplot as plt

warnings.filterwarnings("ignore", category=UserWarning)
INPUT_FILE = "books_dataset.csv"

def main():
    if not os.path.exists(INPUT_FILE):
        print("Missing books_dataset.csv. Copy it from Task 1 into this folder, then run again.")
        return

    df = pd.read_csv(INPUT_FILE)
    original_rows, original_cols = df.shape
    df.columns = [c.strip().lower().replace(" ", "_") for c in df.columns]

    expected = ["title", "price_gbp", "availability", "rating",
                "product_url", "category", "upc", "stock_count"]
    for col in expected:
        if col not in df.columns:
            df[col] = pd.NA

    df["price_gbp"] = pd.to_numeric(df["price_gbp"], errors="coerce")
    df["rating"] = pd.to_numeric(df["rating"], errors="coerce")
    df["stock_count"] = pd.to_numeric(
        df["stock_count"].astype("string").str.extract(r"(\\d+)")[0],
        errors="coerce"
    )

    missing = df.isna().sum()
    duplicate_urls = int(df["product_url"].dropna().duplicated().sum())
    duplicate_titles = int(df["title"].dropna().duplicated().sum())
    invalid_prices = int((df["price_gbp"].notna() & (df["price_gbp"] < 0)).sum())
    invalid_ratings = int((df["rating"].notna() & ~df["rating"].between(1, 5)).sum())

    prices = df["price_gbp"].dropna()
    outliers = 0
    if len(prices) >= 4:
        q1, q3 = prices.quantile([.25, .75])
        iqr = q3 - q1
        outliers = int(((df["price_gbp"] < q1 - 1.5 * iqr) |
                        (df["price_gbp"] > q3 + 1.5 * iqr)).sum())

    clean = df.drop_duplicates().drop_duplicates(subset=["product_url"], keep="first")
    clean.to_csv("books_cleaned.csv", index=False, encoding="utf-8-sig")

    with open("eda_summary.txt", "w", encoding="utf-8") as f:
        f.write("TASK 2: EXPLORATORY DATA ANALYSIS (EDA)\\n" + "=" * 45 + "\\n\\n")
        f.write("QUESTIONS INVESTIGATED\\n")
        f.write("1. What are the dataset dimensions and data types?\\n")
        f.write("2. Which fields contain missing values?\\n")
        f.write("3. What are typical, minimum and maximum prices?\\n")
        f.write("4. How are ratings distributed?\\n")
        f.write("5. Do average prices vary by category?\\n")
        f.write("6. Are there duplicates, invalid values or outlier candidates?\\n\\n")
        f.write(f"Original rows: {original_rows}\\nOriginal columns: {original_cols}\\n")
        f.write(f"Cleaned rows: {len(clean)}\\n\\n")
        f.write("DATA TYPES\\n" + df.dtypes.astype(str).to_string() + "\\n\\n")
        f.write("MISSING VALUES\\n" + missing.to_string() + "\\n\\n")
        f.write("DATA QUALITY CHECKS\\n")
        f.write(f"Duplicate product URLs: {duplicate_urls}\\n")
        f.write(f"Duplicate titles: {duplicate_titles}\\n")
        f.write(f"Negative prices: {invalid_prices}\\n")
        f.write(f"Ratings outside 1-5: {invalid_ratings}\\n")
        f.write(f"Price outlier candidates by IQR: {outliers}\\n\\n")
        f.write("PRICE SUMMARY (GBP)\\n")
        f.write(prices.describe().to_string() if not prices.empty else "No valid numeric prices")
        f.write("\\n\\nRATING COUNTS\\n")
        f.write(df["rating"].value_counts(dropna=False).sort_index().to_string() + "\\n\\n")
        if df["category"].notna().any():
            summary = df.groupby("category")["price_gbp"].agg(["count", "mean", "median"])
            f.write("CATEGORY PRICE SUMMARY (GBP)\\n" + summary.to_string() + "\\n\\n")
        f.write("HYPOTHESIS CHECKS\\n")
        f.write("H1: Prices are non-negative: " + ("PASS" if invalid_prices == 0 else "REVIEW") + "\\n")
        f.write("H2: Ratings are between 1 and 5: " + ("PASS" if invalid_ratings == 0 else "REVIEW") + "\\n")
        f.write("H3: Product URLs are unique after cleaning: PASS\\n\\n")
        f.write("NOTES\\n- IQR outliers are candidates for review, not automatically errors.\\n")
        f.write("- Missing stock counts may mean the page does not expose a count in parsed text.\\n")
        f.write("- Category differences are descriptive and do not prove causation.\\n")
        f.write("- Findings depend on the CSV generated by Task 1.\\n")

    if not prices.empty:
        plt.figure()
        prices.plot(kind="hist", bins=20, edgecolor="black")
        plt.title("Book Price Distribution")
        plt.xlabel("Price (£)")
        plt.ylabel("Number of books")
        plt.tight_layout()
        plt.savefig("price_distribution.png", dpi=150)
        plt.close()

    ratings = df["rating"].dropna().value_counts().sort_index()
    if not ratings.empty:
        plt.figure()
        ratings.plot(kind="bar", edgecolor="black")
        plt.title("Book Ratings")
        plt.xlabel("Rating (1–5)")
        plt.ylabel("Number of books")
        plt.tight_layout()
        plt.savefig("rating_counts.png", dpi=150)
        plt.close()

    if df["category"].notna().any() and not prices.empty:
        means = df.groupby("category")["price_gbp"].mean().sort_values(ascending=False)
        plt.figure(figsize=(10, 6))
        means.plot(kind="bar", edgecolor="black")
        plt.title("Average Book Price by Category")
        plt.xlabel("Category")
        plt.ylabel("Average price (£)")
        plt.xticks(rotation=45, ha="right")
        plt.tight_layout()
        plt.savefig("category_average_price.png", dpi=150)
        plt.close()

    print(f"EDA completed: {original_rows} original rows; {len(clean)} cleaned rows.")
    print("See eda_summary.txt, books_cleaned.csv, and generated PNG charts.")

if __name__ == "__main__":
    main()
